export function getCompanyById(id: string): Company | undefined {
  return COMPANIES.find(c => c.id === id);
}

export function getRelatedCompanies(company: Company): Company[] {
  return company.competitors
    .map(id => getCompanyById(id))
    .filter((c): c is Company => c !== undefined)
    .slice(0, 4);
}

export function getCompaniesByIndustry(industry: string): Company[] {
  return COMPANIES.filter(c => c.industry === industry);
}
